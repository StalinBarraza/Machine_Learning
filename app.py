# Los cuatro archivos .joblib se encuentran junto a app.py
CARPETA = Path(__file__).resolve().parent

@st.cache_resource
def cargar_recursos():
    """Carga y cachea los estimadores y codificadores del modelo entrenado."""
    scaler = load(CARPETA / 'scaler.joblib')
    encoder = load(CARPETA / 'encoder.joblib')
    label_encoder = load(CARPETA / 'label_encoder.joblib')
    model = load(CARPETA / 'model.joblib')
    return scaler, encoder, label_encoder, model

try:
    scaler, encoder, label_encoder, model = cargar_recursos()
    recursos_cargados = True
except Exception as e:
    st.error(f"Error al cargar los archivos del modelo: {e}")
    st.info("Ubica scaler.joblib, encoder.joblib, label_encoder.joblib y model.joblib en la misma carpeta que app.py.")
    recursos_cargados = False

